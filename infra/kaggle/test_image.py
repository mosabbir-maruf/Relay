def _png_chunk(tag: bytes, data: bytes) -> bytes:
    chunk_body = tag + data
    crc = zlib.crc32(chunk_body) & 0xFFFFFFFF
    return struct.pack(">I", len(data)) + chunk_body + struct.pack(">I", crc)


def generate_test_png(text: str = "RELAY GLM OCR TEST 123", scale: int = 4) -> bytes:
    """
    Generates a high-contrast grayscale PNG containing visible text.
    Uses pure Python standard library (no Pillow required).
    """
    # Try Pillow if available for smoother rendering, else fall back to bitmap rasterizer
    try:
        from PIL import Image, ImageDraw

        font_size = 28
        padding = 32
        # Use default PIL bitmap font
        img = Image.new("RGB", (len(text) * 18 + padding * 2, 80), color=(255, 255, 255))
        draw = ImageDraw.Draw(img)
        draw.text((padding, 24), text, fill=(0, 0, 0))
        import io

        buf = io.BytesIO()
        img.save(buf, format="PNG")
        return buf.getvalue()
    except Exception:
        pass

    # Pure Python bitmap rasterizer fallback
    char_w = 6 * scale
    char_h = 8 * scale
    pad_x = 24
    pad_y = 20
    width = len(text) * char_w + pad_x * 2
    height = char_h + pad_y * 2

    # 255 = white background, 0 = black text
    grid = [[255] * width for _ in range(height)]

    for idx, char in enumerate(text.upper()):
        glyph = BITMAP_FONT.get(char, BITMAP_FONT[" "])
        x_base = pad_x + idx * char_w
        for row_idx, row_byte in enumerate(glyph):
            for col_idx in range(5):
                if (row_byte >> (4 - col_idx)) & 1:
                    for sy in range(scale):
                        for sx in range(scale):
                            y = pad_y + row_idx * scale + sy
                            x = x_base + col_idx * scale + sx
                            if 0 <= y < height and 0 <= x < width:
                                grid[y][x] = 0

    # Encode as 8-bit grayscale PNG
    raw_scanlines = bytearray()
    for row in grid:
        raw_scanlines.append(0)  # Filter type 0 (None)
        raw_scanlines.extend(row)

    compressed = zlib.compress(bytes(raw_scanlines), level=6)
    ihdr_data = struct.pack(">IIBBBBB", width, height, 8, 0, 0, 0, 0)

    png_bytes = (
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", ihdr_data)
        + _png_chunk(b"IDAT", compressed)
        + _png_chunk(b"IEND", b"")
    )
    return png_bytes


def generate_test_data_uri(text: str = "RELAY GLM OCR TEST 123") -> str:
    """Returns a base64 data URI string suitable for OpenAI-compatible multimodal requests."""
    png = generate_test_png(text)
    b64 = base64.b64encode(png).decode("utf-8")
    return f"data:image/png;base64,{b64}"


